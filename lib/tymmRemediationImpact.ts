/**
 * Rubric remediation is NOT proof of learning or a causal treatment effect.
 * This module only joins verifiable student-scoped human assessments by
 * submission IDs, criterion identity and the timeline of accepted follow-up.
 */
import {performanceTaskById} from './tymmPerformanceTasks';
import {readableRubric} from './tymmDelayedTransfer';
import {actionReviews} from './tymmActionEvidenceReview';

export type RemediationEvidenceRow={id:string;createdAt:Date;payload:unknown};
export type RemediationImpactStatus=
 'ACTION_NOT_VERIFIED'|'AWAITING_INDEPENDENT_MEASUREMENT'|
 'TRANSFER_BEFORE_ACTION'|'OBSERVED_AFTER_ACTION'|'SOURCE_NOT_VERIFIABLE';
export type RemediationImpact={
  assignmentId:string;taskId:string;criterionId:string;criterionLabel:string;
  status:RemediationImpactStatus;
  originalScore:number|null;independentScore:number|null;change:number|null;
  evidenceAt:string|null;comparedSubmissionId:string|null;
  statement:string;
  limitations:string;
};
const LIMITATIONS='Bu sonuç yalnız aynı rubrik ölçütündeki iki insan puanının zamansal karşılaştırmasıdır; telafinin etkisini, psikometrik eşdeğerliği veya kalıcı öğrenmeyi kanıtlamaz.';
function obj(v:unknown):Record<string,unknown>{
 return v&&typeof v==='object'&&!Array.isArray(v)?v as Record<string,unknown>:{};
}
function date(v:unknown):number|null{
 if(typeof v!=='string')return null;
 const ms=Date.parse(v);
 return Number.isFinite(ms)?ms:null;
}
function scoreById(review:unknown,criterionId:string):number|null{
 const rubric=readableRubric(review);
 return rubric?.criterionScores.find(x=>x.id===criterionId)?.score??null;
}
function impact(action:RemediationEvidenceRow,rows:readonly RemediationEvidenceRow[]):RemediationImpact|null{
 const p=obj(action.payload);
 if(p.type!=='TYMM_RUBRIC_ACTION')return null;
 const assignmentId=action.id,taskId=String(p.taskId||''),criterionId=String(p.criterionId||'');
 const task=performanceTaskById(taskId,Number(p.taskVersion));
 if(!task||p.grade!==task.grade||!task.criteria.some(c=>c.id===criterionId))return null;
 const criterionLabel=task.criteria.find(c=>c.id===criterionId)!.label;
 const original=rows.find(x=>x.id===p.reviewSubmissionId);
 const originalMeta=obj(original?.payload);
 const originalType=String(originalMeta.type||'');
 const originalValid=['TYMM_PERFORMANCE_REVIEWED','TYMM_TRANSFER_REVIEWED'].includes(originalType)&&
  originalMeta.taskId===taskId&&originalMeta.taskVersion===task.version&&originalMeta.grade===task.grade;
 const originalScore=originalValid?scoreById(obj(originalMeta.review),criterionId):null;
 const originalReviewedAt=originalValid?date(obj(originalMeta.review).reviewedAt):null;
 const sourcePrecedesAction=Boolean(original&&originalReviewedAt!==null&&
   originalReviewedAt>=original.createdAt.getTime()&&originalReviewedAt<=action.createdAt.getTime());
 const base={assignmentId,taskId,criterionId,criterionLabel,originalScore,
  independentScore:null as number|null,change:null as number|null,
  evidenceAt:null as string|null,comparedSubmissionId:null as string|null,
  limitations:LIMITATIONS};
 if(!originalValid||!sourcePrecedesAction||originalScore===null||originalScore>1||
   Number(p.originalRubricScore)!==originalScore){
   return {...base,status:'SOURCE_NOT_VERIFIABLE',
    statement:'Bu görevin kaynak rubriği doğrulanamadı; gelişim karşılaştırması yapılmıyor.'};
 }
 const approved=actionReviews(p).filter(r=>r.decision==='ACCEPT').at(-1);
 if(p.status!=='VERIFIED'||!approved)
   return {...base,status:'ACTION_NOT_VERIFIED',
     statement:'Telafi henüz koç tarafından kabul edilmiş bir çalışma olarak doğrulanmadı.'};
 const acceptedAt=date(approved.reviewedAt);
 if(acceptedAt===null||acceptedAt<action.createdAt.getTime())
   return {...base,status:'SOURCE_NOT_VERIFIABLE',
     statement:'Telafi kabul zaman damgası doğrulanamadı.'};
 // A transfer review is meaningful here only if this particular rubric action
 // was generated by the original baseline and the transfer was SUBMITTED after acceptance.
 if(originalType!=='TYMM_PERFORMANCE_REVIEWED')
   return {...base,status:'AWAITING_INDEPENDENT_MEASUREMENT',
     statement:'Bu telafi ikinci ölçümün ardından atandı; daha sonraki bağımsız bir ölçüm kaydı henüz yok.'};
 const linked=rows.filter(row=>{
   const x=obj(row.payload);
   return x.type==='TYMM_TRANSFER_REVIEWED'&&
    x.baselineSubmissionId===original!.id&&
    x.taskId===taskId&&x.taskVersion===task.version&&x.grade===task.grade;
 });
 const later=linked.filter(row=>row.createdAt.getTime()>=acceptedAt);
 const comparable=later.map(row=>{
   const x=obj(row.payload);
   return {row,score:scoreById(obj(x.review),criterionId)};
 }).find(x=>x.score!==null);
 if(!comparable){
   return {...base,status:linked.some(x=>x.createdAt.getTime()<acceptedAt)?'TRANSFER_BEFORE_ACTION':'AWAITING_INDEPENDENT_MEASUREMENT',
     statement:linked.some(x=>x.createdAt.getTime()<acceptedAt)
       ?'Bağımsız ikinci görev telafi kabulünden önce teslim edilmiş; telafi sonrası gelişim diye sunulamaz.'
       :'Koç telafiyi kabul etti; sonrasında aynı kazanım için bağımsız ve puanlanmış ikinci görev henüz bulunmuyor.'};
 }
 const current=comparable.score!;
 const change=current-originalScore;
 return {...base,status:'OBSERVED_AFTER_ACTION',independentScore:current,change,
   evidenceAt:comparable.row.createdAt.toISOString(),comparedSubmissionId:comparable.row.id,
   statement:change>0?'İlgili ölçütte sonraki bağımsız rubrik puanı yükseldi.':
     change<0?'İlgili ölçütte sonraki bağımsız rubrik puanı geriledi.':
     'İlgili ölçütte sonraki bağımsız rubrik puanı değişmedi.'};
}
export function buildRemediationImpactReport(rows:readonly RemediationEvidenceRow[]){
 const impacts=rows.flatMap(x=>{const result=impact(x,rows);return result?[result]:[]});
 const observed=impacts.filter(x=>x.status==='OBSERVED_AFTER_ACTION');
 return {
  impacts,
  summary:{
   totalAssigned:impacts.length,
   accepted:impacts.filter(x=>x.status==='OBSERVED_AFTER_ACTION'||
    x.status==='AWAITING_INDEPENDENT_MEASUREMENT'||x.status==='TRANSFER_BEFORE_ACTION').length,
   independentlyReassessed:observed.length,
   increased:observed.filter(x=>x.change!==null&&x.change>0).length,
   unchanged:observed.filter(x=>x.change===0).length,
   decreased:observed.filter(x=>x.change!==null&&x.change<0).length,
   missingFollowUp:impacts.filter(x=>x.status==='AWAITING_INDEPENDENT_MEASUREMENT'||
     x.status==='TRANSFER_BEFORE_ACTION').length
  },
  caveat:LIMITATIONS
 };
}
